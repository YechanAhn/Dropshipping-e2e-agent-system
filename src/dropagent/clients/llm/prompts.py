def format_prompt(template: str, **kwargs: Any) -> str:
    """
    프롬프트 템플릿에 인자를 채워 완성된 프롬프트를 반환합니다.

    누락된 키는 빈 문자열로 대체하여 KeyError를 방지합니다.

    Args:
        template: 포맷 플레이스홀더가 포함된 프롬프트 템플릿 문자열.
        **kwargs: 플레이스홀더를 대체할 키-값 쌍.

    Returns:
        포맷이 완료된 프롬프트 문자열.

    Examples:
        >>> prompt = format_prompt(
        ...     PRODUCT_TRANSLATION_PROMPT,
        ...     product_name_en="Wireless Bluetooth Earbuds",
        ...     category="Electronics",
        ... )
        >>> "Wireless Bluetooth Earbuds" in prompt
        True
    """

    class SafeDict(dict):
        """존재하지 않는 키에 대해 빈 문자열을 반환하는 딕셔너리."""

        def __missing__(self, key: str) -> str:
            return ""

    return template.format_map(SafeDict(**kwargs))
